package com.finance.manager.dto.request;

import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import lombok.Data;

/**
 * DTO for POST /api/auth/register
 * Why separate DTOs from Entities? 
 * 1. Entities map to DB — DTOs map to API contract. They evolve independently.
 * 2. Prevents accidentally exposing internal fields (like hashed password in response).
 * 3. Allows different validation rules for create vs update.
 */
@Data
public class RegisterRequest {

    @NotBlank(message = "Username is required")
    @Email(message = "Username must be a valid email address")
    private String username;

    @NotBlank(message = "Password is required")
    @Size(min = 6, message = "Password must be at least 6 characters")
    private String password;

    @NotBlank(message = "Full name is required")
    private String fullName;

    @NotBlank(message = "Phone number is required")
    @Pattern(regexp = "^\\+?[0-9]{7,15}$", message = "Phone number must be valid")
    private String phoneNumber;
}